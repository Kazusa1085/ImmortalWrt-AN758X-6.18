static u32 an7581_pcs_pon_readout_eo(struct airoha_pcs_priv *priv, int index)
{
	struct regmap *pma = priv->pcs_pma[index];
	u32 eye, ready;
	u32 left, right;

	/* Latch four FLL read-only values before toggling the RO latch. */
	regmap_set_bits(pma, AIROHA_PCS_PMA_RX_FLL_6,
			AIROHA_PCS_PMA_LNX_SW_FLL_4_LATCH_EN |
			AIROHA_PCS_PMA_LNX_SW_FLL_3_LATCH_EN |
			AIROHA_PCS_PMA_LNX_SW_FLL_2_LATCH_EN |
			AIROHA_PCS_PMA_LNX_SW_FLL_1_LATCH_EN);
	udelay(50);
	regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_FLL_6,
			  AIROHA_PCS_PMA_LNX_SW_FLL_4_LATCH_EN |
			  AIROHA_PCS_PMA_LNX_SW_FLL_3_LATCH_EN |
			  AIROHA_PCS_PMA_LNX_SW_FLL_2_LATCH_EN |
			  AIROHA_PCS_PMA_LNX_SW_FLL_1_LATCH_EN);
	regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_DEBUG_0,
			  AIROHA_PCS_PMA_RO_TOGGLE);
	udelay(100);
	regmap_set_bits(pma, AIROHA_PCS_PMA_RX_DEBUG_0,
			AIROHA_PCS_PMA_RO_TOGGLE);

	regmap_read(pma, AIROHA_PCS_PMA_RX_TORGS_DEBUG_10, &eye);
	left = FIELD_GET(AIROHA_PCS_PMA_EYE_EL, eye);
	right = FIELD_GET(AIROHA_PCS_PMA_EYE_ER, eye);
	regmap_read(pma, AIROHA_PCS_PMA_RX_TORGS_DEBUG_5, &ready);
	if (!(ready & AIROHA_PCS_PMA_HEO_RDY)) {
		/* Pulse the analog CDR LPF reset when HEO rejects a peaking point. */
		regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_DISB_MODE_0,
				  AIROHA_PCS_PMA_DISB_DA_XPON_CDR_LPF_RSTB);
		regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_FORCE_MODE_0,
				  AIROHA_PCS_PMA_FORCE_DA_XPON_CDR_LPF_RSTB);
		udelay(500);
		regmap_set_bits(pma, AIROHA_PCS_PMA_RX_FORCE_MODE_0,
				AIROHA_PCS_PMA_FORCE_DA_XPON_CDR_LPF_RSTB);
		udelay(500);
	}

	return abs((int)right - (int)left);
}

