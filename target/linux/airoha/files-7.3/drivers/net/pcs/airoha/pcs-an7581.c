static void an7581_pcs_pon_oscal(struct airoha_pcs_priv *priv, int index)
{
	struct regmap *pma = priv->pcs_pma[index];

	/* Offset calibration forces FBCK lock and enables the OSCAL clock and reset. */
	regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_DISB_MODE_8,
			  AIROHA_PCS_PMA_DISB_FBCK_LOCK);
	regmap_set_bits(pma, AIROHA_PCS_PMA_RX_FORCE_MODE_9,
			AIROHA_PCS_PMA_FORCE_FBCK_LOCK);
	regmap_set_bits(pma, AIROHA_PCS_PMA_PXP_JCPLL_SDM_SCAN_RSTB,
			AIROHA_PCS_PMA_FORCE_SEL_DA_RX_OSCAL_CKON |
			AIROHA_PCS_PMA_FORCE_DA_RX_OSCAL_CKON);
	regmap_set_bits(pma, AIROHA_PCS_PMA_PXP_RX_OSCAL_EN,
			AIROHA_PCS_PMA_FORCE_SEL_DA_RX_OSCAL_RSTB |
			AIROHA_PCS_PMA_FORCE_DA_RX_OSCAL_RSTB |
			AIROHA_PCS_PMA_FORCE_SEL_DA_RX_OSCAL_EN |
			AIROHA_PCS_PMA_FORCE_DA_RX_OSCAL_EN);
	udelay(200);

	/* Return control to the sequencer after an RX_OS_EN edge starts calibration. */
	regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_CTRL_SEQUENCE_DISB_CTRL_0,
			  AIROHA_PCS_PMA_DISB_RX_OS_EN);
	regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_CTRL_SEQUENCE_DISB_CTRL_1,
			  AIROHA_PCS_PMA_DISB_RX_OS_RDY);
	regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_CTRL_SEQUENCE_FORCE_CTRL_0,
			  AIROHA_PCS_PMA_FORCE_RX_OS_EN);
	regmap_clear_bits(pma, AIROHA_PCS_PMA_RX_CTRL_SEQUENCE_FORCE_CTRL_1,
			  AIROHA_PCS_PMA_FORCE_RX_OS_RDY);
	regmap_set_bits(pma, AIROHA_PCS_PMA_RX_CTRL_SEQUENCE_FORCE_CTRL_0,
			AIROHA_PCS_PMA_FORCE_RX_OS_EN);
}

